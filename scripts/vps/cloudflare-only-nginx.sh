#!/usr/bin/env bash
# Lets only Cloudflare reach the API's nginx site, so nobody can skip Cloudflare (DDoS protection,
# WAF) by calling the server's IP directly, or spoof the CF-Connecting-IP header the API uses for
# rate limits. Other sites on the server are not touched: the site includes the generated snippet.
#
#   sudo bash scripts/vps/cloudflare-only-nginx.sh
#
# Writes /etc/nginx/snippets/cloudflare-only.conf from Cloudflare's published ranges and reloads
# nginx when the config is valid. On any failure the previous snippet is kept. Safe to run from
# cron (/etc/cron.weekly) to pick up range changes. The site's server blocks need:
#   include /etc/nginx/snippets/cloudflare-only.conf;
set -euo pipefail

SNIPPET=/etc/nginx/snippets/cloudflare-only.conf
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

{
  echo "# Generated by scripts/vps/cloudflare-only-nginx.sh on $(date -u +%FT%TZ). Do not edit."
  for list in ips-v4 ips-v6; do
    ranges="$(curl -fsS --max-time 20 "https://www.cloudflare.com/$list")"
    # Refuse an empty or malformed list rather than locking every visitor out.
    [ "$(printf '%s\n' "$ranges" | grep -cE '^[0-9a-f:.]+/[0-9]+$')" -ge 5 ] || {
      echo "unexpected $list response" >&2
      exit 1
    }
    printf '%s\n' "$ranges" | grep -E '^[0-9a-f:.]+/[0-9]+$' | sed 's/^/allow /; s/$/;/'
  done
  echo "deny all;"
} > "$TMP"

mkdir -p "$(dirname "$SNIPPET")"
if [ -f "$SNIPPET" ] && cmp -s <(grep -v '^#' "$SNIPPET") <(grep -v '^#' "$TMP"); then
  echo "Cloudflare ranges unchanged."
  exit 0
fi

BACKUP=""
[ -f "$SNIPPET" ] && BACKUP="$(mktemp)" && cp "$SNIPPET" "$BACKUP"
install -m 644 "$TMP" "$SNIPPET"
if nginx -t 2>/dev/null; then
  systemctl reload nginx
  echo "Updated $SNIPPET and reloaded nginx."
else
  echo "nginx -t failed; restoring the previous snippet." >&2
  if [ -n "$BACKUP" ]; then cp "$BACKUP" "$SNIPPET"; else rm -f "$SNIPPET"; fi
  exit 1
fi
